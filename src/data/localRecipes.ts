function toRecipe(seed: Seed, index: number): NormalizedRecipe {
  return {
    id: `local:${index + 1}`,
    provider: "local" as ProviderId,
    title: seed.title,
    cuisine: seed.cuisine,
    category: seed.category,
    minutes: seed.minutes,
    instructions: seed.instructions,
    ingredients: seed.ingredients.map((name) => ({
      name,
      canonical: canonicalName(name),
    })),
  };
}

export const LOCAL_RECIPES: NormalizedRecipe[] = SEEDS.map(toRecipe);
